import SwiftUI

struct TitleValue<Content: View>: View {
    let title: String
    let content: () -> Content

    init(_ title: String, @ViewBuilder content: @escaping () -> Content) {
        self.title = title
        self.content = content
    }

    var body: some View {
        VStack(alignment: .leading) {
            Text(title)
                .font(.footnote)
                .opacity(0.75)
            HStack(content: content)
        }
    }
}
