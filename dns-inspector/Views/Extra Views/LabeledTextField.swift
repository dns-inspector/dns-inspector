import SwiftUI

struct LabeledTextField<Content: View>: View {
    let label: String
    let content: () -> Content

    init(label: String, @ViewBuilder content: @escaping () -> Content) {
        self.label = label
        self.content = content
    }

    var body: some View {
        if #available(iOS 16, *) {
            LabeledContent(self.label) {
                self.content()
            }
        } else {
            HStack {
                Text(self.label)
                self.content()
            }
        }
    }
}
